# =============================================================================
# Helper-функции для работы с клетками
# =============================================================================

def square(file: int, rank: int) -> int:
    """Преобразовать file (0-7) и rank (0-7) в индекс клетки (0-63)."""
    return rank * 8 + file


def file_of(sq: int) -> int:
    """Вернуть file (0-7) клетки."""
    return sq % 8


def rank_of(sq: int) -> int:
    """Вернуть rank (0-7) клетки."""
    return sq // 8


def square_name(sq: int) -> str:
    """Вернуть название клетки в шахматной нотации (например, 'e4')."""
    files = "abcdefgh"
    ranks = "12345678"
    return f"{files[file_of(sq)]}{ranks[rank_of(sq)]}"


# =============================================================================
# Utility-функции для фигур
# =============================================================================

def get_piece_color(piece: int) -> int:
    """Вернуть цвет фигуры: WHITE, BLACK или 0 если EMPTY."""
    if piece == 0:
        return 0
    return WHITE if piece > 0 else BLACK


def get_piece_type(piece: int) -> int:
    """Вернуть тип фигуры (1-6), игнорируя цвет."""
    return abs(piece)


def is_piece_type(piece: int, piece_type: int) -> bool:
    """Проверить, является ли фигура заданного типа (без учёта цвета)."""
    return abs(piece) == piece_type
